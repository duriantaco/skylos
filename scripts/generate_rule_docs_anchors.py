#!/usr/bin/env python3
"""Regenerate skylos/rules/docs_anchors.py from skylos-docs rules-reference.mdx.

Each rule ID maps to the heading that documents it on
https://docs.skylos.dev/rules-reference: its own "### SKY-XXXX · Name"
section when there is one, otherwise the quick-reference table section that
lists it. Heading IDs follow Docusaurus (github-slugger) rules.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

RULE_ID_RE = re.compile(r"SKY-CIRC|SKY-SCA-[A-Z]+[0-9]{3}|SKY-[A-Z]+[0-9]{3}")
HEADING_RE = re.compile(r"^(#{2,6})\s+(.*?)\s*#*\s*$")
FENCE_RE = re.compile(r"^\s*(```|~~~)")
OUTPUT = Path(__file__).resolve().parents[1] / "skylos" / "rules" / "docs_anchors.py"


def _plain_heading(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[*_]{1,3}([^*_]+)[*_]{1,3}", r"\1", text)


def _kept(char: str) -> bool:
    if char in " -_":
        return True
    return unicodedata.category(char)[0] in {"L", "N", "M"}


def slugify(text: str, seen: dict[str, int]) -> str:
    base = "".join(
        char for char in _plain_heading(text).strip().lower() if _kept(char)
    ).replace(" ", "-")
    count = seen.get(base, 0)
    seen[base] = count + 1
    if count:
        return f"{base}-{count}"
    return base


def rule_anchors(text: str) -> dict[str, str]:
    seen: dict[str, int] = {}
    detailed: dict[str, str] = {}
    listed: dict[str, str] = {}
    section = None
    in_fence = False
    for line in text.splitlines():
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = HEADING_RE.match(line)
        if heading:
            slug = slugify(heading.group(2), seen)
            ids = RULE_ID_RE.findall(heading.group(2))
            if ids:
                for rule_id in ids:
                    detailed.setdefault(rule_id, slug)
            else:
                section = slug
            continue
        if section and line.lstrip().startswith("|"):
            first_cell = line.strip().strip("|").split("|")[0]
            for rule_id in RULE_ID_RE.findall(first_cell):
                listed.setdefault(rule_id, section)
    return {**listed, **detailed}


def render(anchors: dict[str, str]) -> str:
    lines = [
        '"""Rule documentation anchors on https://docs.skylos.dev/rules-reference.',
        "",
        "Generated by scripts/generate_rule_docs_anchors.py from skylos-docs",
        "docs/rules-reference.mdx; regenerate it when that page changes.",
        '"""',
        "",
        "RULE_DOCS_ANCHORS = {",
    ]
    for rule_id in sorted(anchors):
        lines.append(f'    "{rule_id}": "{anchors[rule_id]}",')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("rules_reference", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = args.rules_reference.read_text(encoding="utf-8")
    rendered = render(rule_anchors(text))
    if args.check:
        current = ""
        if args.output.exists():
            current = args.output.read_text(encoding="utf-8")
        if current != rendered:
            print(f"{args.output} is out of date", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
