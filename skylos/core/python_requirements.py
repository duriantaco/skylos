"""Static reading of pip requirements files.

Requirements files are data. Nothing here installs, executes, or downloads
anything. ``-r``/``-c`` includes are followed only to regular files inside the
project root, with bounded depth and file count.

Compiled lock files (pip-compile or ``uv pip compile`` output) pin the whole
environment, so most of their entries are transitive. They are recognised by
their header, ``--hash`` options, or ``# via`` annotations.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from pathlib import Path

from skylos.core.safe_cache_io import read_text_no_symlink

MAX_REQUIREMENTS_BYTES = 5_000_000
MAX_INCLUDED_REQUIREMENTS_FILES = 64
MAX_REQUIREMENTS_INCLUDE_DEPTH = 8

_NAME_RE = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9_.-]*)")
_COMMENT_RE = re.compile(r"(^|\s+)#.*$")
_INCLUDE_RE = re.compile(
    r"^(?P<option>-r|--requirement|-c|--constraint)(?:\s*=\s*|\s*)(?P<target>\S+)\s*$"
)
_EDITABLE_RE = re.compile(r"^(?:-e|--editable)(?:\s*=\s*|\s+)(?P<target>\S+)")
_PER_REQUIREMENT_OPTION_RE = re.compile(
    r"\s--(?:hash|global-option|install-option|config-settings|config-setting)"
    r"(?:\s*=\s*|\s+)\S+"
)
_EGG_RE = re.compile(r"[#&]egg=([A-Za-z0-9][A-Za-z0-9_.-]*)")
_VIA_RE = re.compile(r"^#\s*via(?:\s+(?P<rest>.*))?$")
_VIA_CONTINUATION_RE = re.compile(r"^#\s{2,}(?P<rest>\S.*)$")
_COMPILED_HEADER_RE = re.compile(
    r"autogenerated by (?:pip-compile|uv)|uv pip compile|pip-compile", re.IGNORECASE
)
PRIVATE_INDEX_OPTIONS = (
    "--index-url",
    "--extra-index-url",
    "--find-links",
    "--no-index",
    "-i ",
    "-i=",
    "-f ",
    "-f=",
)
# Global options that change how pip installs, not which modules exist.
HARMLESS_OPTIONS = (
    "--require-hashes",
    "--pre",
    "--prefer-binary",
    "--only-binary",
    "--no-binary",
    "--trusted-host",
    "--use-feature",
    "--progress-bar",
)


def normalize_distribution_name(name) -> str:
    if not name:
        return ""
    return re.sub(r"[-_.]+", "-", str(name).strip().lower())


@dataclass(frozen=True)
class RequirementLine:
    """One requirement, with continuations joined and options removed."""

    name: str
    normalized: str
    spec: str
    line: int
    snippet: str
    path: Path
    via: tuple = ()
    url: bool = False

    @property
    def direct_in_lock(self) -> bool:
        """pip-compile/uv mark direct inputs with ``# via -r <file>``."""
        return any(item.startswith(("-r ", "-r=")) for item in self.via)


@dataclass
class RequirementsFile:
    path: Path
    requirements: list = field(default_factory=list)
    includes: list = field(default_factory=list)
    editables: list = field(default_factory=list)
    private_index: bool = False
    unsupported_lines: int = 0
    compiled: bool = False


def _logical_lines(text):
    """Yield (first_line_number, joined_text, physical_first_line)."""
    buffer = []
    start = None
    first = ""
    for number, raw in enumerate(text.splitlines(), start=1):
        if start is None:
            start = number
            first = raw.strip()
        stripped = raw.rstrip()
        if stripped.endswith("\\") and not stripped.lstrip().startswith("#"):
            buffer.append(stripped[:-1])
            continue
        buffer.append(stripped)
        yield start, " ".join(part.strip() for part in buffer), first
        buffer, start, first = [], None, ""
    if buffer:
        yield start, " ".join(part.strip() for part in buffer), first


def is_compiled_requirements_text(text: str) -> bool:
    head = "\n".join(text.splitlines()[:8])
    if _COMPILED_HEADER_RE.search(head):
        return True
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("--hash") or " --hash" in stripped:
            return True
        if _VIA_RE.match(stripped):
            return True
    return False


def parse_requirements_text(text: str, path: Path) -> RequirementsFile:
    parsed = RequirementsFile(Path(path))
    parsed.compiled = is_compiled_requirements_text(text)
    last = None
    via: list = []
    collecting_via = False

    def flush():
        nonlocal last, via
        if last is not None:
            parsed.requirements.append(
                RequirementLine(
                    last["name"],
                    normalize_distribution_name(last["name"]),
                    last["spec"],
                    last["line"],
                    last["snippet"],
                    parsed.path,
                    tuple(via),
                    last["url"],
                )
            )
        last, via = None, []

    for number, logical, first in _logical_lines(text):
        stripped = logical.strip()
        if not stripped:
            collecting_via = False
            continue
        if stripped.startswith("#"):
            via_match = _VIA_RE.match(stripped)
            if via_match and last is not None:
                rest = (via_match.group("rest") or "").strip()
                if rest:
                    via.append(rest)
                collecting_via = True
                continue
            continuation = _VIA_CONTINUATION_RE.match(stripped)
            if collecting_via and continuation and last is not None:
                via.append(continuation.group("rest").strip())
                continue
            collecting_via = False
            continue
        collecting_via = False
        flush()
        content = _COMMENT_RE.sub("", stripped).strip()
        if not content:
            continue
        include = _INCLUDE_RE.match(content)
        if include:
            kind = (
                "constraint"
                if include.group("option") in ("-c", "--constraint")
                else "requirement"
            )
            parsed.includes.append((kind, include.group("target"), number))
            continue
        editable = _EDITABLE_RE.match(content)
        if editable:
            parsed.editables.append(editable.group("target"))
            continue
        if content.startswith(PRIVATE_INDEX_OPTIONS) or content in ("-i", "-f"):
            parsed.private_index = True
            continue
        if content.startswith(HARMLESS_OPTIONS):
            continue
        if content.startswith("-"):
            parsed.unsupported_lines += 1
            continue
        spec = _PER_REQUIREMENT_OPTION_RE.sub("", " " + content).strip()
        url = False
        name = None
        if re.match(r"^(?:git\+|hg\+|svn\+|bzr\+|https?://|file:|\.{0,2}/)", spec):
            egg = _EGG_RE.search(spec)
            name = egg.group(1) if egg else None
            url = True
        else:
            match = _NAME_RE.match(spec)
            name = match.group(1) if match else None
            url = " @ " in spec or spec.startswith(f"{name}@") if name else False
        if not name:
            parsed.unsupported_lines += 1
            continue
        last = {
            "name": name,
            "spec": spec,
            "line": number,
            "snippet": first,
            "url": url,
        }
    flush()
    return parsed


def read_requirements_file(path, *, max_bytes=MAX_REQUIREMENTS_BYTES):
    text = read_text_no_symlink(
        path, max_bytes=max_bytes, encoding="utf-8", errors="ignore"
    )
    if text is None:
        return None
    return parse_requirements_text(text, Path(path))


def _contained_include(base_file: Path, target: str, root: Path):
    """(path to read, resolved path) for an include inside ``root``, or None.

    The unresolved path is what gets read, so a symlinked file is refused by
    ``read_text_no_symlink``; the resolved path keeps a symlinked directory
    from escaping ``root``.
    """
    if "://" in target or target.startswith(("git+", "hg+", "svn+", "bzr+")):
        return None
    target = target.removeprefix("file:")
    candidate = Path(target)
    if not candidate.is_absolute():
        candidate = base_file.parent / candidate
    candidate = Path(os.path.abspath(candidate))
    try:
        resolved = Path(os.path.realpath(candidate))
        resolved.relative_to(root)
    except (OSError, ValueError):
        return None
    return candidate, resolved


@dataclass
class RequirementsTree:
    """A requirements file plus every ``-r``/``-c`` file it reaches."""

    files: list = field(default_factory=list)
    # path -> "requirement" or "constraint" (constraint if only reached via -c)
    kinds: dict = field(default_factory=dict)
    unresolved_includes: list = field(default_factory=list)
    limit_reached: bool = False

    def requirements(self, *, include_constraints=True):
        for parsed in self.files:
            if not include_constraints and self.kinds.get(parsed.path) == "constraint":
                continue
            yield from parsed.requirements


def read_requirements_tree(
    path,
    *,
    root,
    max_files=MAX_INCLUDED_REQUIREMENTS_FILES,
    max_depth=MAX_REQUIREMENTS_INCLUDE_DEPTH,
    visited=None,
):
    """Read ``path`` and follow its includes inside ``root``.

    ``visited`` (resolved paths) may be shared between calls so one scan
    reads each file once. Symlinked files are never read.
    """
    tree = RequirementsTree()
    try:
        root = Path(os.path.realpath(root))
        start = Path(os.path.abspath(path))
        resolved_start = Path(os.path.realpath(start))
        resolved_start.relative_to(root)
    except (OSError, ValueError):
        return tree
    seen = visited if visited is not None else set()
    read_as = {}
    pending = [(start, resolved_start, "requirement", 0)]
    while pending:
        current, resolved, kind, depth = pending.pop(0)
        if resolved in seen:
            # A file reached as a requirement anywhere is a requirement.
            earlier = read_as.get(resolved)
            if kind == "requirement" and earlier is not None:
                tree.kinds[earlier] = "requirement"
            continue
        if len(seen) >= max_files:
            tree.limit_reached = True
            break
        seen.add(resolved)
        parsed = read_requirements_file(current)
        if parsed is None:
            if current != start:
                tree.unresolved_includes.append(str(current))
            continue
        read_as[resolved] = parsed.path
        tree.files.append(parsed)
        tree.kinds[parsed.path] = kind
        for include_kind, target, _line in parsed.includes:
            include = _contained_include(current, target, root)
            if include is None:
                tree.unresolved_includes.append(target)
                continue
            if depth + 1 > max_depth:
                tree.limit_reached = True
                continue
            child_kind = "constraint" if kind == "constraint" else include_kind
            pending.append((*include, child_kind, depth + 1))
    return tree


def lock_source_files(parsed: RequirementsFile, root) -> list:
    """The ``.in`` inputs a compiled lock file names in ``# via -r <file>``.

    Falls back to the sibling ``<stem>.in`` when the lock names none.
    """
    sources = []
    try:
        root = Path(os.path.realpath(root))
    except OSError:
        return sources
    names = []
    for requirement in parsed.requirements:
        for item in requirement.via:
            if item.startswith(("-r ", "-r=")):
                names.append(item[2:].lstrip(" =").strip())
    for name in dict.fromkeys(names):
        include = _contained_include(parsed.path, name, root)
        if (
            include is not None
            and include[0].suffix == ".in"
            and include[0] not in sources
        ):
            sources.append(include[0])
    if not sources:
        include = _contained_include(
            parsed.path, parsed.path.with_suffix(".in").name, root
        )
        if include is not None and include[0].is_file():
            sources.append(include[0])
    return sources


# ---------------------------------------------------------------------------
# setuptools declarations: ``setup.cfg`` and ``setup.py``.
#
# Both are read statically. ``setup.cfg`` is INI data; ``setup.py`` is parsed
# with ``ast`` and only literal values (or module-level names bound to
# literals) are read. Nothing is executed. Anything that cannot be read that
# way (``attr:``, computed lists, ``setup(**kwargs)``) marks the declaration
# ``dynamic``: its requirement list is open-ended.
# ---------------------------------------------------------------------------

SETUPTOOLS_REQUIREMENT_KEYS = ("install_requires", "setup_requires", "tests_require")
_MARKER_NAMES = frozenset(
    {
        "extra",
        "implementation_name",
        "implementation_version",
        "os_name",
        "platform_machine",
        "platform_python_implementation",
        "platform_release",
        "platform_system",
        "platform_version",
        "python_full_version",
        "python_version",
        "sys_platform",
    }
)


@dataclass
class SetuptoolsRequirements:
    """Requirement strings declared for setuptools, with their source lines.

    ``install`` is what the package needs at run time; ``extras`` are
    optional groups; ``setup``/``tests`` are build and test requirements.
    Each entry is ``(requirement string, line)``.
    """

    path: Path
    name: str | None = None
    install: list = field(default_factory=list)
    extras: dict = field(default_factory=dict)
    setup: list = field(default_factory=list)
    tests: list = field(default_factory=list)
    dynamic: bool = False

    def all_requirements(self):
        yield from self.install
        for entries in self.extras.values():
            yield from entries
        yield from self.setup
        yield from self.tests

    def names(self, *, runtime_only=False):
        entries = self.install if runtime_only else self.all_requirements()
        names = set()
        for spec, _line in entries:
            name = requirement_name(spec)
            if name:
                names.add(normalize_distribution_name(name))
        return names


def requirement_name(spec):
    """Distribution name of a PEP 508 string; None for markers or options."""
    if not isinstance(spec, str):
        return None
    spec = spec.strip()
    if not spec or spec.startswith(("#", "-")):
        return None
    match = _NAME_RE.match(spec)
    if match is None:
        return None
    name = match.group(1)
    if name.lower() in _MARKER_NAMES:
        return None
    return name


def _setuptools_list(value):
    """setuptools' ``list-semi``: one per line, else ``;``-separated."""
    chunks = value.splitlines() if "\n" in value else value.split(";")
    items = []
    for chunk in chunks:
        chunk = chunk.strip()
        if not chunk or chunk.startswith("#"):
            continue
        items.append(chunk)
    return items


_SECTION_RE = re.compile(r"^\s*\[([^\]]+)\]")


def _line_locator(text):
    """Find the line of a requirement inside one INI section."""
    sections = []
    current = None
    for raw in text.splitlines():
        header = _SECTION_RE.match(raw)
        if header:
            current = header.group(1).strip()
        sections.append(current)
    lines = text.splitlines()
    used = set()

    def locate(item, section):
        for number, raw in enumerate(lines, start=1):
            if number in used or sections[number - 1] != section:
                continue
            stripped = raw.strip()
            value = stripped.split("=", 1)[1].strip() if "=" in stripped else None
            if stripped == item or value == item:
                used.add(number)
                return number
        return 0

    return locate


def parse_setup_cfg_text(text, path, *, root=None):
    """``[options]`` requirements and ``[options.extras_require]`` groups.

    ``file:`` values are read as requirements files only when they are
    regular files inside ``root`` (default: the ``setup.cfg`` directory).
    """
    import configparser

    path = Path(path)
    parsed = SetuptoolsRequirements(path)
    config = configparser.ConfigParser(interpolation=None, strict=False)
    try:
        config.read_string(text)
    except (configparser.Error, ValueError):
        parsed.dynamic = True
        return parsed
    if config.has_option("metadata", "name"):
        name = config.get("metadata", "name").strip()
        if name and not name.startswith(("attr:", "file:")):
            parsed.name = name
    locate = _line_locator(text)
    include_root = Path(root) if root is not None else path.parent

    def entries(value, section):
        value = value.strip()
        if value.startswith("file:"):
            found = []
            for target in value[5:].split(","):
                target = target.strip()
                include = _contained_include(path, target, include_root)
                requirements = read_requirements_file(include[0]) if include else None
                if requirements is None:
                    parsed.dynamic = True
                    continue
                if requirements.includes or requirements.unsupported_lines:
                    parsed.dynamic = True
                found.extend((req.spec, 0) for req in requirements.requirements)
            return found
        if value.startswith("attr:"):
            parsed.dynamic = True
            return []
        return [(item, locate(item, section)) for item in _setuptools_list(value)]

    if config.has_section("options"):
        for key, target in zip(
            SETUPTOOLS_REQUIREMENT_KEYS, (parsed.install, parsed.setup, parsed.tests)
        ):
            if config.has_option("options", key):
                target.extend(entries(config.get("options", key), "options"))
    if config.has_section("options.extras_require"):
        for extra, value in config.items("options.extras_require"):
            parsed.extras.setdefault(extra, []).extend(
                entries(value, "options.extras_require")
            )
    return parsed


def read_setup_cfg(path, *, root=None, max_bytes=MAX_REQUIREMENTS_BYTES):
    text = read_text_no_symlink(
        path, max_bytes=max_bytes, encoding="utf-8", errors="ignore"
    )
    if text is None:
        return None
    return parse_setup_cfg_text(text, Path(path), root=root)


def _literal_strings(node, bindings, depth=0):
    """``[(string, line)]`` for a static list/tuple, or None if not static."""
    import ast

    if depth > 8:
        return None
    if isinstance(node, ast.Name):
        bound = bindings.get(node.id)
        return None if bound is None else _literal_strings(bound, bindings, depth + 1)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left = _literal_strings(node.left, bindings, depth + 1)
        right = _literal_strings(node.right, bindings, depth + 1)
        return None if left is None or right is None else left + right
    if isinstance(node, (ast.List, ast.Tuple)):
        values = []
        for element in node.elts:
            if not (
                isinstance(element, ast.Constant) and isinstance(element.value, str)
            ):
                return None
            values.append((element.value, element.lineno))
        return values
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return [(item, node.lineno) for item in _setuptools_list(node.value)]
    return None


def parse_setup_py_text(text, path):
    """Literal ``setup(...)`` keywords; None when the file is not Python 3.

    Module-level names bound once to literals (``REQUIRES = [...]``) and
    ``+`` of such lists are followed; nothing else is evaluated.
    """
    import ast

    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        return None
    parsed = SetuptoolsRequirements(Path(path))
    bindings = {}
    rebound = set()
    for statement in tree.body:
        targets = []
        if isinstance(statement, ast.Assign):
            targets, value = statement.targets, statement.value
        elif isinstance(statement, ast.AnnAssign) and statement.value is not None:
            targets, value = [statement.target], statement.value
        for target in targets:
            if isinstance(target, ast.Name):
                if target.id in bindings:
                    rebound.add(target.id)
                bindings[target.id] = value
    for name in rebound:
        bindings.pop(name, None)

    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        function = node.func
        if not (
            (isinstance(function, ast.Name) and function.id == "setup")
            or (isinstance(function, ast.Attribute) and function.attr == "setup")
        ):
            continue
        for keyword in node.keywords:
            if keyword.arg is None:
                parsed.dynamic = True  # setup(**metadata)
                continue
            if (
                keyword.arg == "name"
                and isinstance(keyword.value, ast.Constant)
                and isinstance(keyword.value.value, str)
            ):
                parsed.name = keyword.value.value
            elif keyword.arg in SETUPTOOLS_REQUIREMENT_KEYS:
                values = _literal_strings(keyword.value, bindings)
                if values is None:
                    parsed.dynamic = True
                    continue
                target = {
                    "install_requires": parsed.install,
                    "setup_requires": parsed.setup,
                    "tests_require": parsed.tests,
                }[keyword.arg]
                target.extend(values)
            elif keyword.arg == "extras_require":
                value = keyword.value
                if isinstance(value, ast.Name):
                    value = bindings.get(value.id)
                if not isinstance(value, ast.Dict):
                    parsed.dynamic = True
                    continue
                for key, group in zip(value.keys, value.values):
                    values = _literal_strings(group, bindings)
                    if (
                        not (
                            isinstance(key, ast.Constant) and isinstance(key.value, str)
                        )
                        or values is None
                    ):
                        parsed.dynamic = True
                        continue
                    parsed.extras.setdefault(key.value, []).extend(values)
    return parsed


def read_setup_py(path, *, max_bytes=MAX_REQUIREMENTS_BYTES):
    text = read_text_no_symlink(
        path, max_bytes=max_bytes, encoding="utf-8", errors="ignore"
    )
    if text is None:
        return None
    return parse_setup_py_text(text, Path(path))
