package symbols

import "testing"

func TestFunctionReachabilityUsesObjectsAndLiveOwners(t *testing.T) {
	cases := []struct {
		name   string
		files  map[string]string
		states map[string]string
	}{
		{
			name: "unrooted recursion and mutual calls",
			files: map[string]string{"main.go": `package main
func main() { keep() }
func keep() {}
func staleA() { staleB() }
func staleB() { staleA() }
func self() { self() }
`},
			states: map[string]string{"main": "reachable", "keep": "reachable", "staleA": "unreachable", "staleB": "unreachable", "self": "unreachable"},
		},
		{
			name: "local callback and parameter do not refer to package function",
			files: map[string]string{"main.go": `package main
func main() {
 stale := func() {}
 stale()
 consume := func(stale int) { _ = stale }
 consume(1)
 keep()
}
func stale() {}
func keep() {}
`},
			states: map[string]string{"main": "reachable", "keep": "reachable", "stale": "unreachable"},
		},
		{
			name: "same spelled field is not a function use",
			files: map[string]string{"main.go": `package main
type state struct { stale int }
func main() { value := state{}; println(value.stale) }
func stale() {}
`},
			states: map[string]string{"main": "reachable", "stale": "unreachable"},
		},
		{
			name: "receiver owners and method values",
			files: map[string]string{"main.go": `package main
type left struct{}
type right struct{}
func (left) run() {}
func (right) run() {}
func main() { var x left; callback := x.run; callback() }
`},
			states: map[string]string{"main": "reachable", "left.run": "reachable", "right.run": "unreachable"},
		},
		{
			name: "generic method instantiation uses its declaration object",
			files: map[string]string{"main.go": `package main
type Box[T any] struct{}
func (b *Box[T]) reset() {}
func main() { var box Box[int]; callback := box.reset; callback() }
func unused() {}
`},
			states: map[string]string{"main": "reachable", "Box.reset": "reachable", "unused": "unreachable"},
		},
		{
			name: "function values returned or initialized remain live",
			files: map[string]string{"main.go": `package demo
var callback = initialized
func initialized() {}
func API() func() { return returned }
func returned() {}
func unusedOwner() func() { return deadValue }
func deadValue() {}
`},
			states: map[string]string{"API": "reachable", "initialized": "reachable", "returned": "reachable", "unusedOwner": "unreachable", "deadValue": "unreachable"},
		},
		{
			name: "init and package initializer calls",
			files: map[string]string{"main.go": `package demo
var value = makeValue()
func makeValue() int { return 1 }
func init() { initialized() }
func initialized() {}
func unused() {}
`},
			states: map[string]string{"init": "reachable", "initialized": "reachable", "makeValue": "reachable", "unused": "unreachable"},
		},
		{
			name: "test references and benchmark callbacks",
			files: map[string]string{
				"main.go":      "package demo\nfunc helper() {}\nfunc unused() {}\n",
				"main_test.go": "package demo\nimport \"testing\"\nfunc TestValue(t *testing.T) { helper() }\n",
			},
			states: map[string]string{"helper": "reachable", "unused": "unreachable"},
		},
		{
			name: "generated consumers remain roots",
			files: map[string]string{
				"main.go":      "package demo\nfunc helper() {}\nfunc unused() {}\n",
				"generated.go": "// Code generated by a tool. DO NOT EDIT.\npackage demo\nfunc generated() { helper() }\n",
			},
			states: map[string]string{"helper": "reachable", "generated": "reachable", "unused": "unreachable"},
		},
		{
			name: "referenced private interface methods remain possible uses",
			files: map[string]string{"main.go": `package demo
type runner interface { run() }
type worker struct{}
func (worker) run() {}
func API() runner { return worker{} }
func unused() {}
`},
			states: map[string]string{"API": "reachable", "worker.run": "reachable", "unused": "unreachable"},
		},
		{
			name: "private interface dispatch from main retains implementation",
			files: map[string]string{"main.go": `package main
type runner interface { run() }
type worker struct{}
func (worker) run() {}
func invoke(r runner) { r.run() }
func main() { invoke(worker{}) }
func unused() {}
`},
			states: map[string]string{"main": "reachable", "invoke": "reachable", "worker.run": "reachable", "unused": "unreachable"},
		},
		{
			name: "anonymous private interface dispatch retains implementation",
			files: map[string]string{"main.go": `package main
type worker struct{}
func (worker) run() {}
func invoke(r interface{ run() }) { r.run() }
func main() { invoke(worker{}) }
func unused() {}
`},
			states: map[string]string{"main": "reachable", "invoke": "reachable", "worker.run": "reachable", "unused": "unreachable"},
		},
		{
			name: "alternate build consumers are retained without target execution",
			files: map[string]string{
				"main.go":    "package demo\nfunc helper() {}\nfunc unused() {}\n",
				"feature.go": "//go:build skylos_not_enabled\n\npackage demo\nfunc Feature() { helper() }\n",
			},
			states: map[string]string{"Feature": "reachable", "helper": "reachable", "unused": "unreachable"},
		},
		{
			name: "incompatible alternate builds disable proof",
			files: map[string]string{
				"main.go":    "package demo\nfunc helper() {}\nfunc API() {}\n",
				"feature.go": "//go:build skylos_not_enabled\n\npackage demo\nfunc API() { helper() }\n",
			},
			states: map[string]string{"helper": "", "API": ""},
		},
		{
			name: "missing external imports disable proof",
			files: map[string]string{"main.go": `package demo
import "example.invalid/not-installed"
func API() { notinstalled.Run(helper) }
func helper() {}
func staleA() { staleB() }
func staleB() { staleA() }
`},
			states: map[string]string{"API": "", "helper": "", "staleA": "", "staleB": ""},
		},
		{
			name: "valid project imports retain typed callback use",
			files: map[string]string{
				"main.go":    "package main\nimport \"example.com/demo/lib\"\nfunc main() { lib.API(callback) }\nfunc callback() {}\n",
				"lib/lib.go": "package lib\nfunc API(callback func()) { callback() }\nfunc unused() {}\n",
			},
			states: map[string]string{"main": "reachable", "callback": "reachable", "lib.API": "reachable", "lib.unused": "unreachable"},
		},
		{
			name:   "assembly use disables proof",
			files:  map[string]string{"main.go": "package demo\nfunc helper() {}\n", "entry.s": "// Assembly may refer to helper.\n"},
			states: map[string]string{"helper": ""},
		},
		{
			name:   "linkname retains its callback chain",
			files:  map[string]string{"main.go": "package demo\n//go:linkname hook external.hook\nfunc hook() { helper() }\nfunc helper() {}\nfunc unused() {}\n"},
			states: map[string]string{"hook": "reachable", "helper": "reachable", "unused": "unreachable"},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			writeTestFile(t, root, "go.mod", "module example.com/demo\n\ngo 1.22\n")
			for name, source := range tc.files {
				writeTestFile(t, root, name, source)
			}
			result, err := Extract(root)
			if err != nil {
				t.Fatal(err)
			}
			for name, state := range tc.states {
				found := false
				for _, def := range result.Defs {
					if def.Name == name {
						found = true
						if def.Reachability != state {
							t.Errorf("%s reachability = %q, want %q", name, def.Reachability, state)
						}
					}
				}
				if !found {
					t.Errorf("missing definition %s", name)
				}
			}
		})
	}
}
