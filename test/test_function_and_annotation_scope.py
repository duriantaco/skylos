"""Function metrics and annotation advice judge shipped, hand-written code.

Covers: test, docs and example scope for the five function metrics;
annotation advice outside examples, for read parameters and for
value-returning properties; generated JS/TS.
"""

import ast
import textwrap

import pytest

from skylos.rules.quality.complexity import CognitiveComplexityRule, ComplexityRule
from skylos.rules.quality.logic_maintainability import TooManyReturnsRule
from skylos.rules.quality.nesting import NestingRule
from skylos.rules.quality.practices import TypeAnnotationPracticeRule
from skylos.rules.quality.structure import FunctionLengthRule


def _function_findings(rule, source, filename, project_root=None):
    source = textwrap.dedent(source)
    tree = ast.parse(source)
    context = {"filename": str(filename), "source": source, "project_root": project_root}
    return [row for node in ast.walk(tree) for row in rule.visit_node(node, context) or ()]


BRANCHY = """
def branchy(x):
""" + "".join(
    f"    if x == {i}:\n        if x > {i}:\n            return {i}\n" for i in range(12)
) + "    return None\n"


@pytest.mark.parametrize(
    "rule",
    [
        ComplexityRule(), CognitiveComplexityRule(), NestingRule(threshold=1),
        FunctionLengthRule(max_lines=5), TooManyReturnsRule(),
    ],
)
def test_function_metrics_skip_test_and_docs_code(tmp_path, rule):
    (tmp_path / ".git").mkdir()
    shipped = tmp_path / "pkg" / "logic.py"
    suite = tmp_path / "tests" / "test_logic.py"
    docs = tmp_path / "docs" / "examples" / "logic.py"
    for path in (shipped, suite, docs):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(BRANCHY)
    assert _function_findings(rule, BRANCHY, shipped, tmp_path)
    assert _function_findings(rule, BRANCHY, suite, tmp_path) == []
    assert _function_findings(rule, BRANCHY, docs, tmp_path) == []


def _annotation_findings(source, filename, project_root):
    source = textwrap.dedent(source)
    tree = ast.parse(source)
    context = {"filename": str(filename), "source": source, "project_root": project_root}
    return TypeAnnotationPracticeRule().visit_node(tree, context) or []


PARTLY_TYPED = """
def build(name: str, options, _info):
    return name, options
"""


def test_annotation_advice_skips_examples_and_docs(tmp_path):
    (tmp_path / ".git").mkdir()
    example = tmp_path / "docs_src" / "tutorial" / "app.py"
    shipped = tmp_path / "pkg" / "app.py"
    for path in (example, shipped):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(PARTLY_TYPED)
    (tmp_path / "pyproject.toml").write_text(
        '[tool.mypy]\nfiles = ["pkg"]\ndisallow_incomplete_defs = true\n'
    )
    assert _annotation_findings(PARTLY_TYPED, shipped, tmp_path)
    assert _annotation_findings(PARTLY_TYPED, example, tmp_path) == []


def test_required_annotations_include_unread_placeholder_parameters(tmp_path):
    path = tmp_path / "app.py"
    path.write_text(PARTLY_TYPED)
    (tmp_path / "pyproject.toml").write_text(
        '[tool.mypy]\nfiles = ["app.py"]\ndisallow_incomplete_defs = true\n'
    )
    (finding,) = [
        row
        for row in _annotation_findings(PARTLY_TYPED, path, tmp_path)
        if row["rule_id"] == "SKY-T101"
    ]
    assert finding["value"] == "options, _info"

    read = PARTLY_TYPED.replace("return name, options", "return name, options, _info")
    (finding,) = [
        row
        for row in _annotation_findings(read, path, tmp_path)
        if row["rule_id"] == "SKY-T101"
    ]
    assert finding["value"] == "options, _info"


def test_required_annotations_include_setters_and_value_returns(tmp_path):
    source = """
    class Session:
        @property
        def auth(self) -> str:
            return self._auth

        @auth.setter
        def auth(self, value: str):
            self._auth = value

        def rename(self, value: str):
            return value.upper()
    """
    path = tmp_path / "app.py"
    (tmp_path / "pyproject.toml").write_text(
        '[tool.mypy]\nfiles = ["app.py"]\ndisallow_incomplete_defs = true\n'
    )
    rows = _annotation_findings(source, path, tmp_path)
    assert [(row["rule_id"], row["simple_name"]) for row in rows] == [
        ("SKY-T102", "auth"),
        ("SKY-T102", "rename")
    ]


@pytest.mark.parametrize(
    "header",
    [
        "// Generated from dutch.sbl by Snowball 3.0.1 - https://snowballstem.org/\n",
        "/*\n * Generated by PEG.js 0.9.0.\n */\n",
    ],
)
def test_generated_header_alone_keeps_javascript_function_metrics(tmp_path, header):
    from skylos.visitors.languages.typescript import scan_typescript_file

    body = "function stem(word) {\n" + "".join(
        f"  if (word === '{i}') {{ return {i}; }}\n" for i in range(15)
    ) + "  return word;\n}\n"
    for name, prefix, expected in (("gen.js", header, True), ("hand.js", "", True)):
        path = tmp_path / "lib" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(prefix + body, encoding="utf-8")
        rows = scan_typescript_file(str(path))[6]
        assert any(row["rule_id"] == "SKY-Q301" for row in rows) is expected


@pytest.mark.parametrize(
    "header",
    ["// Generated from schema.def by ExampleGenerator 1.0\n",
     "/* Generated by ExampleGenerator 1.0. */\n"],
)
def test_generator_name_comment_does_not_expand_type_safety_exclusions(tmp_path, header):
    from skylos.visitors.languages.typescript import scan_typescript_file

    path = tmp_path / "service.ts"
    path.write_text(header + "const value = input as any as User;\n", encoding="utf-8")
    rows = scan_typescript_file(str(path))[6]
    assert any(row["rule_id"] == "SKY-T103" for row in rows)
