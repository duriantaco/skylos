"""Generated declaration policy does not exempt executable or unsafe source."""

import pytest

from skylos.visitors.languages.typescript.core import TypeScriptCore
from skylos.visitors.languages.typescript.generated_declarations import is_generated_declaration_output
from skylos.visitors.languages.typescript.quality_signals import scan_quality_signals


HEADER = "/* eslint-disable */\n// Generated by a declaration tool\n"


def _rules(source, filename="types.d.ts"):
    core = TypeScriptCore(filename, source.encode())
    return {row["rule_id"] for row in scan_quality_signals(core.root_node, core.source, filename, core.lang)}


@pytest.mark.parametrize("body", [
    "export {}; declare global { const display: typeof import('./helpers').display; }",
    "export {}; declare module 'vue' { interface GlobalComponents { Panel: typeof import('./Panel.vue')['default']; } }",
    "import type { Route } from 'router'; declare module 'router/auto' { export interface Paths { home: Route; } } export {};",
    "export interface Service { read(): string; }",
])
def test_generated_declaration_suppressions_are_not_authored_lint_bypasses(body):
    assert "SKY-L035" not in _rules(HEADER + body)


@pytest.mark.parametrize("filename, header, body", [
    ("app.ts", HEADER, "export const count = 1;"),
    ("types.d.ts", "/* eslint-disable */\n", "export interface Service {}"),
    ("types.d.ts", HEADER, "export const count = fetch('/api');"),
    ("types.d.ts", HEADER, "declare global { const count = fetch('/api'); }"),
    ("types.d.ts", HEADER, "export class Service { read() { return 1; } }"),
    ("types.d.ts", HEADER, "declare global { fetch('/api'); }"),
    ("types.d.ts", HEADER, "declare global { let count: number; count++; }"),
    ("types.d.ts", HEADER, "export const count = 1;"),
])
def test_comments_and_suffixes_do_not_hide_executable_code(filename, header, body):
    assert "SKY-L035" in _rules(header + body, filename)


def test_public_declaration_quality_remains_visible():
    rules = _rules(HEADER + "export interface Service { read(): any; }")
    assert "SKY-L035" not in rules
    assert "SKY-T106" in rules


def test_generated_marker_in_code_text_is_not_a_header():
    core = TypeScriptCore("types.d.ts", b'const description = "Generated by a declaration tool";')
    assert not is_generated_declaration_output(core.root_node, core.source, "types.d.ts")
