def _compiled_lock(entries):
    lines = [
        "# This file was autogenerated by uv via the following command:",
        "#    ./docker/compile_requirements.sh",
    ]
    for name, version, via in entries:
        lines += [
            f"{name}=={version} \\",
            "    --hash=sha256:" + "a" * 64 + " \\",
            "    --hash=sha256:" + "b" * 64,
            f"    # via {via}",
        ]
    return "\n".join(lines) + "\n"


def _pontoon_shaped(tmp_path, source):
    repo = tmp_path / "repo"
    _write(repo / "requirements.txt", "# Heroku\n-r requirements/1-prod.txt\n")
    _write(repo / "requirements" / "1-prod.txt", _compiled_lock(LOCK_ENTRIES))
    _write(repo / "setup.py", 'from setuptools import setup\nsetup(name="site")\n')
    return repo, _write(repo / "site" / "views.py", source)


def test_compiled_lock_reached_through_include_declares_imports(monkeypatch, tmp_path):
    repo, source = _pontoon_shaped(tmp_path, REAL_IMPORTS)
    fetched = _stub_registry(monkeypatch)

    findings = dep.scan_python_dependency_hallucinations(repo, [source])

    assert findings == []
    assert findings.unverified_imports == {}
    # Declared names and the curated mapping settle these without PyPI.
    assert fetched == []


def test_setup_py_build_backend_import_is_not_a_dependency(monkeypatch, tmp_path):
    repo, _ = _pontoon_shaped(tmp_path, "import django\n")
    _stub_registry(monkeypatch, installed={"setuptools": {"setuptools"}})

    findings = dep.scan_python_dependency_hallucinations(repo, [repo / "setup.py"])

    assert findings == []


def test_made_up_package_is_still_hallucinated_when_providers_are_known(
    monkeypatch, tmp_path
):
    repo = tmp_path / "repo"
    _write(repo / "requirements.txt", "requests==2.32.0 \\\n    --hash=sha256:abc\n")
    source = _write(repo / "app.py", "import requests\nimport fastjsonx_turbo\n")
    _stub_registry(
        monkeypatch,
        pypi={"requests": "exists"},
        wheels={"requests": {"modules": ["requests"]}},
    )

    findings = dep.scan_python_dependency_hallucinations(repo, [source])

    assert _findings(findings) == [
        (dep.RULE_ID_HALLUCINATION, dep.SEV_CRITICAL, "fastjsonx_turbo")
    ]


def test_made_up_package_is_still_reported_in_a_large_lock(monkeypatch, tmp_path):
    # Too many declared distributions to inspect them all, but none is named
    # like the import: it stays visible instead of becoming a note.
    repo, source = _pontoon_shaped(tmp_path, REAL_IMPORTS + "import fastjsonx_turbo\n")
    _stub_registry(monkeypatch)

    findings = dep.scan_python_dependency_hallucinations(repo, [source])

    assert _findings(findings) == [
        (dep.RULE_ID_UNDECLARED, dep.SEV_MEDIUM, "fastjsonx_turbo")
    ]
    assert findings[0]["message"].startswith(
        "Possible hallucinated import 'fastjsonx_turbo'"
    )


def test_unverifiable_import_is_a_summary_note_not_a_finding(monkeypatch, tmp_path):
    repo = tmp_path / "repo"
    _write(
        repo / "requirements.txt",
        "--extra-index-url https://pypi.acme/simple\nacme-sdk==1.0\n",
    )
    source = _write(repo / "app.py", "import acme_internal_tools\n")
    _stub_registry(monkeypatch)

    findings = dep.scan_python_dependency_hallucinations(repo, [source])

    assert findings == []
    assert findings.unverified_imports == {
        "acme_internal_tools": "open_ended_declarations"
    }


def test_namespace_root_alone_is_never_accepted_by_name(monkeypatch, tmp_path):
    repo = tmp_path / "repo"
    _write(
        repo / "pyproject.toml",
        '[project]\nname = "site"\ndependencies = ["google-auth==2.0"]\n',
    )
    source = _write(
        repo / "app.py",
        "from google.auth import credentials\nimport google.fake_portion\n",
    )
    inventory = pypi_wheel_modules.module_inventory(
        ["google/auth/__init__.py", "google/oauth2/__init__.py"]
    )
    _stub_registry(
        monkeypatch,
        wheels={"google-auth": {**inventory, "complete_for_requirement": True}},
    )

    findings = dep.scan_python_dependency_hallucinations(repo, [source])

    assert _findings(findings) == [
        (dep.RULE_ID_HALLUCINATION, dep.SEV_CRITICAL, "google")
    ]


def test_installed_metadata_naming_another_distribution_is_kept(monkeypatch, tmp_path):
    # mlx is declared, mlx_lm comes from the undeclared mlx-lm: a name
    # resemblance must not hide that.
    repo = tmp_path / "repo"
    _write(repo / "requirements.txt", "mlx>=0.20\n")
    source = _write(repo / "app.py", "import mlx\nimport mlx_lm\n")
    _stub_registry(
        monkeypatch,
        pypi={"mlx-lm": "exists"},
        installed={"mlx": {"mlx"}, "mlx_lm": {"mlx-lm"}},
    )

    findings = dep.scan_python_dependency_hallucinations(repo, [source])

    assert [(f["rule_id"], f["symbol"]) for f in findings] == [
        (dep.RULE_ID_UNDECLARED, "mlx_lm")
    ]


@pytest.mark.parametrize(
    "dist, path",
    [
        ("beautifulsoup4", "bs4"),
        ("djangorestframework", "rest_framework.serializers"),
        ("django-allauth", "allauth.account"),
        ("PyYAML", "yaml"),
        ("Pillow", "PIL.Image"),
        ("python-dateutil", "dateutil.parser"),
        ("django-guardian", "guardian.shortcuts"),
        ("PyJWT", "jwt"),
        ("google-cloud-translate", "google.cloud.translate_v3"),
        ("moz.l10n", "moz.l10n.formats"),
    ],
)
def test_distribution_names_map_to_import_paths(dist, path):
    assert path_is_provided(path, distribution_import_paths(dist))


@pytest.mark.parametrize(
    "dist, path",
    [
        ("google-cloud-translate", "google.protobuf"),
        ("google-auth", "google"),
        ("requests-mock", "requests"),
        ("django-allauth", "django"),
    ],
)
def test_distribution_names_do_not_overreach(dist, path):
    provided = distribution_import_paths(dist)
    if path == "google":
        # ``import google`` alone: a parent of a provided namespace portion.
        assert "google" not in provided
    else:
        assert not path_is_provided(path, provided)


@pytest.mark.parametrize(
    "dist, made_up",
    [("pydantic", "dantic"), ("flask-login", "login"), ("pytest", "test")],
)
def test_name_rules_never_invent_an_import(dist, made_up):
    # A hallucinated import must not pass because a declared name contains it.
    assert not path_is_provided(made_up, distribution_import_paths(dist))


def test_installed_metadata_maps_names_without_claiming_shared_roots():
    installed = {"bs4": {"beautifulsoup4"}, "google": {"protobuf", "google-auth"}}
    paths = distribution_import_paths(
        "beautifulsoup4", installed_modules=installed, namespace_roots={"google"}
    )
    assert "bs4" in paths
    assert "google" not in distribution_import_paths(
        "protobuf", installed_modules=installed, namespace_roots={"google"}
    )


def test_unverified_imports_reach_the_analysis_summary():
    class _Analyzer:
        def __init__(self):
            self._dependency_import_notes = {
                "unverified_import_count": 2,
                "unverified_imports": ["acme_magic", "shared"],
            }

    result = {"analysis_summary": {}}
    _attach_analysis_reports(_Analyzer(), result)

    assert result["analysis_summary"]["dependency_imports"] == {
        "unverified_import_count": 2,
        "unverified_imports": ["acme_magic", "shared"],
    }
