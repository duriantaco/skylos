"""Requirements includes, compiled lock files, SCA and SKY-U005 (pontoon shape).

On mozilla/pontoon (4.47.2) all 108 U005 findings were wrong (92 transitive
entries of a uv lock file, 16 used direct dependencies) and the Python CVE
scan read nothing because ``requirements.txt`` only says
``-r requirements/1-prod.txt``.
"""

import os

import pytest

from skylos.core.python_requirements import (
    lock_source_files,
    parse_requirements_text,
    read_requirements_tree,
)
from skylos.rules.quality.unused_deps import scan_unused_dependencies
from skylos.rules.sca.vulnerability_scanner import (
    collect_dependencies,
    parse_requirements_txt,
)

LOCK = """\
# This file was autogenerated by uv via the following command:
#    ./docker/compile_requirements.sh
amqp==5.3.1 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via kombu
beautifulsoup4==4.12.3 \\
    --hash=sha256:cccc
    # via -r 0-base.in
django==5.2.18 \\
    --hash=sha256:dddd
    # via
    #   -r 0-base.in
    #   django-allauth
sqlparse==0.5.5 \\
    --hash=sha256:eeee
    # via django
"""


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")  # skylos: ignore[SKY-D324] tmp_path
    return path


def test_compiled_lock_lines_are_joined_and_annotated(tmp_path):
    parsed = parse_requirements_text(LOCK, tmp_path / "1-prod.txt")
    assert parsed.compiled is True
    assert parsed.unsupported_lines == 0
    by_name = {item.normalized: item for item in parsed.requirements}
    assert by_name["django"].spec == "django==5.2.18"
    assert by_name["django"].line == 10
    assert by_name["django"].via == ("-r 0-base.in", "django-allauth")
    assert by_name["django"].direct_in_lock is True
    assert by_name["amqp"].direct_in_lock is False


def test_hand_written_requirements_are_not_a_lock(tmp_path):
    parsed = parse_requirements_text("requests>=2  # http\nflask\n", tmp_path / "r.txt")
    assert parsed.compiled is False
    assert [item.spec for item in parsed.requirements] == ["requests>=2", "flask"]


def test_includes_are_followed_inside_the_root_only(tmp_path):
    root = tmp_path / "repo"
    _write(
        root / "requirements.txt",
        "-r requirements/prod.txt\n-c constraints.txt\n-r ../outside.txt\n",
    )
    _write(root / "requirements" / "prod.txt", "--requirement=base.txt\ndjango==5.2\n")
    _write(root / "requirements" / "base.txt", "requests==2.32.0\n")
    _write(root / "constraints.txt", "urllib3==2.0\n")
    _write(tmp_path / "outside.txt", "evil==1.0\n")

    tree = read_requirements_tree(root / "requirements.txt", root=root)

    assert {item.normalized for item in tree.requirements()} == {
        "django",
        "requests",
        "urllib3",
    }
    assert {
        item.normalized for item in tree.requirements(include_constraints=False)
    } == {"django", "requests"}
    assert tree.unresolved_includes == ["../outside.txt"]


def test_symlinked_include_is_not_read(tmp_path):
    root = tmp_path / "repo"
    target = _write(root / "real.txt", "secretpkg==1.0\n")
    _write(root / "requirements.txt", "-r linked.txt\n")
    try:
        os.symlink(target, root / "linked.txt")
    except OSError:
        pytest.skip("symlinks unavailable")
    tree = read_requirements_tree(root / "requirements.txt", root=root)
    assert list(tree.requirements()) == []


def test_lock_source_files_come_from_via_annotations(tmp_path):
    root = tmp_path / "repo"
    lock = _write(root / "requirements" / "1-prod.txt", LOCK)
    _write(root / "requirements" / "0-base.in", "django\nbeautifulsoup4\n")
    parsed = read_requirements_tree(lock, root=root).files[0]
    assert lock_source_files(parsed, root) == [root / "requirements" / "0-base.in"]


def test_sca_follows_requirement_includes_not_constraints(tmp_path):
    root = tmp_path / "repo"
    _write(root / "requirements.txt", "-r requirements/1-prod.txt\n-c pins.txt\n")
    _write(root / "requirements" / "1-prod.txt", LOCK)
    _write(root / "pins.txt", "urllib3==1.0\n")

    deps = parse_requirements_txt(root / "requirements.txt", root=root)
    assert {(d["name"], d["version"]) for d in deps} == {
        ("amqp", "5.3.1"),
        ("beautifulsoup4", "4.12.3"),
        ("django", "5.2.18"),
        ("sqlparse", "0.5.5"),
    }
    sqlparse = next(d for d in deps if d["name"] == "sqlparse")
    assert sqlparse["file"].endswith("1-prod.txt")
    assert sqlparse["line"] == 15

    inventory = collect_dependencies(root)
    assert inventory.receipt["included_requirements_file_count"] == 1
    assert inventory.receipt["dependency_count"] == 4
    assert inventory.receipt["unresolved_dependency_count"] == 0


def _pontoon_shaped(tmp_path, base_in, sources, extra_files=None):
    root = tmp_path / "repo"
    _write(root / "requirements.txt", "-r requirements/1-prod.txt\n")
    _write(root / "requirements" / "1-prod.txt", LOCK)
    _write(root / "requirements" / "0-base.in", base_in)
    for name, text in (extra_files or {}).items():
        _write(root / name, text)
    files = [_write(root / name, text) for name, text in sources.items()]
    return root, files


def _unused(findings):
    return sorted(item["name"] for item in findings if item["rule_id"] == "SKY-U005")


def test_lock_entries_are_never_flagged_and_direct_inputs_are(tmp_path):
    root, files = _pontoon_shaped(
        tmp_path,
        "django==5.2.18\nbeautifulsoup4==4.12.3\nleftover-lib==1.0\n",
        {
            "app/views.py": "from django.db import models\nfrom bs4 import BeautifulSoup\n"
        },
    )
    findings = scan_unused_dependencies(root, files, location_root=root)
    # amqp/sqlparse are transitive lock pins; leftover-lib is really unused.
    assert _unused(findings) == ["leftover-lib"]
    [finding] = findings
    assert finding["file"].endswith("0-base.in")
    assert finding["line"] == 3


def test_framework_and_command_uses_count(tmp_path):
    base_in = """\
django
django-bmemcached
django-csp
newrelic
zensical
my-console-tool
django-stubs
types-pyyaml
psycopg2
mypkg-plugin
pypydispatcher
python-consul2
sphinx-click
flake8-docstrings
pytest-rerunfailures
pytest-subtests
pytest-click
"""
    root, files = _pontoon_shaped(
        tmp_path,
        base_in,
        {
            "project/settings.py": (
                'INSTALLED_APPS = ["django.contrib.admin"]\n'
                'MIDDLEWARE = ["csp.middleware.CSPMiddleware"]\n'
                'CACHES = {"default": {"BACKEND": '
                '"django_bmemcached.memcached.BMemcached"}}\n'
                "from pydispatch import dispatcher\n"
                "import consul\n"
            ),
            "tests/test_commands.py": (
                "def test_command(cli_runner, subtests):\n"
                "    with subtests.test():\n"
                "        assert cli_runner is not None\n"
            ),
        },
        {
            "Procfile": "web: newrelic-admin run-program gunicorn app.wsgi\n",
            "docker/Dockerfile": (
                "RUN uv pip install -r requirements/1-prod.txt my-console-tool\n"
                "RUN zensical build -f documentation/zensical.toml\n"
            ),
            "mypy.ini": "[mypy]\nplugins =\n    mypy_django_plugin.main\n",
            "docs/conf.py": "extensions = ['sphinx_click']\n",
            "tox.ini": "[testenv]\ncommands = pytest --reruns 3 tests\n",
            "setup.cfg": (
                "[options.entry_points]\nconsole_scripts =\n"
                "    run = mypkg_plugin.cli:main\n"
                "[flake8]\nextend-ignore = D102, D104\n"
            ),
        },
    )
    findings = scan_unused_dependencies(root, files, location_root=root)
    # The Dockerfile only installs my-console-tool; installing is not using.
    assert _unused(findings) == ["my-console-tool"]


def test_hand_written_requirements_behave_as_before(tmp_path):
    root = tmp_path / "repo"
    _write(root / "requirements.txt", "-r base.txt\nflask\n")
    _write(root / "base.txt", "requests\npyserial\n")
    source = _write(root / "app.py", "import requests\nimport flask\n")
    findings = scan_unused_dependencies(root, [source], location_root=root)
    assert _unused(findings) == ["pyserial"]
    assert findings[0]["file"].endswith("base.txt")
    assert findings[0]["line"] == 2
