def test_many_yarn_entries_keep_parser_memory_bounded():
    entry_count = 20_000
    lines = YARN_V1_PREAMBLE.splitlines(True) + [
        part
        for index in range(entry_count)
        for part in (
            f"pkg-{index}@^1:\n",
            '  version "1.0.0"\n',
            f"  integrity {NPM_SRI}\n",
        )
    ]

    tracemalloc.start()
    try:
        approved, contexts = _yarn_integrity_spans(lines)
        _, peak_bytes = tracemalloc.get_traced_memory()
    finally:
        tracemalloc.stop()

    assert len(approved) == entry_count
    assert contexts == {}
    assert peak_bytes < 16 * 1024 * 1024


