def test_missing_edges_and_invalid_metadata_keep_exact_inventory():
    result = parse(
        berry(
            {
                "pkg@npm:^1": package(
                    dependencies={"missing": "npm:^1", "bad": []},
                    peerDependencies="invalid",
                    dependenciesMeta={"missing": {"optional": "yes"}},
                    conditions=[],
                )
            }
        )
    )
    assert [dependency["name"] for dependency in result.dependencies] == ["pkg"]
    assert reasons(result) == {
        "missing_locked_dependency",
        "invalid_package_metadata",
        "invalid_dependency_declaration",
        "invalid_dependency_section",
    }


