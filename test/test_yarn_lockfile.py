def test_reader_uses_bounded_no_symlink_helper(monkeypatch):
    calls = []

    def read(path, **kwargs):
        calls.append((path, kwargs))
        return CLASSIC

    monkeypatch.setattr(yarn_lockfile, "read_text_no_symlink", read)
    assert parse_yarn_lock(Path("yarn.lock")).package_count == 3
    assert calls == [
        (Path("yarn.lock"), {"max_bytes": 10_000_000, "encoding": "utf-8"})
    ]
    monkeypatch.setattr(
        yarn_lockfile, "read_text_no_symlink", lambda *args, **kwargs: None
    )
    with pytest.raises(LockfileParseError, match="cannot be read"):
        parse_yarn_lock(Path("yarn.lock"))
