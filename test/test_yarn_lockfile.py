def test_cyclic_graph_preserves_roots_and_terminates():
    result = parse(
        berry(
            {
                "app@workspace:.": {
                    "resolution": "app@workspace:.",
                    "dependencies": {"a": "npm:^1"},
                },
                "a@npm:^1": package("a", dependencies={"b": "npm:^1"}),
                "b@npm:^1": package("b", dependencies={"a": "npm:^1"}),
            }
        )
    )
    assert result.unresolved == []
    assert len(result.dependencies) == 2
    assert result.dependencies[0]["dependency_kinds"] == ["direct", "transitive"]
    assert all(
        dependency["dependency_roots"] == [""] for dependency in result.dependencies
    )


